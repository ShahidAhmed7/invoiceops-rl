"""Phase 9: scripted-agent baselines and the verifier mutation report (no GPU needed).

    uv run python scripts/local_baselines.py

Writes deterministic reports under reports/local/. Episode files go to runs/ (not committed).
"""

from __future__ import annotations

import json
from pathlib import Path

from invoiceops.cli import main as cli
from invoiceops.evaluation.run import evaluate
from invoiceops.tasks.store import task_ids

AGENTS = ("oracle", "noop", "always_hold", "always_pay", "random")
SPLITS = ("train", "dev", "test")
OUT = Path("reports/local")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for agent in AGENTS:
        for split in SPLITS:
            run_dir = Path("runs/local") / f"{agent}-{split}"
            summary = evaluate(agent, task_ids(split), run_dir, extra_config={"splits": [split]})
            target = OUT / agent / split
            target.mkdir(parents=True, exist_ok=True)
            for name in ("summary.json", "report.md", "config.json"):
                (target / name).write_text((run_dir / name).read_text())
            rows.append((agent, split, summary))
    lines = [
        "# Local baselines (scripted agents)",
        "",
        "Generated by `scripts/local_baselines.py`. One attempt per task; scripted agents are",
        "deterministic. The oracle is privileged (it reads policy parameters directly) and proves",
        "solvability; it is not an agent baseline.",
        "",
        "| Agent | Split | Tasks | Success | Attempts with critical violation "
        "| Exception cases not paid | Clean cases paid correctly |",
        "|---|---|---|---|---|---|---|",
    ]
    for agent, split, s in rows:
        lines.append(
            f"| {agent} | {split} | {s['tasks']} | {100 * s['task_mean_success']:.1f}% | "
            f"{s['attempts_with_critical_violation']} | {s['exception_cases_not_paid']} | "
            f"{s['clean_cases_paid_correctly']} |"
        )
    (OUT / "scripted_baselines.md").write_text("\n".join(lines) + "\n")
    (OUT / "scripted_baselines.json").write_text(
        json.dumps([{"agent": a, "split": sp, **s} for a, sp, s in rows], indent=2, sort_keys=True)
        + "\n"
    )
    cli(["verify-mutations", "--report", str(OUT / "verifier_mutations.md")])


if __name__ == "__main__":
    main()
